CREATE OR REPLACE FUNCTION revoke_agent(user_id_in INTEGER)
RETURNS VOID AS
$$
DECLARE
    roles_to_remove VARCHAR[] := ARRAY['ROLE_AGENT', 'ROLE_ADMIN_ASSISTANT'];
    role_ids_to_remove INTEGER[];
BEGIN
    SELECT ARRAY(
        SELECT id FROM role
        WHERE name = ANY(roles_to_remove)
    ) INTO role_ids_to_remove;

    IF array_length(role_ids_to_remove, 1) IS NOT NULL THEN
        DELETE FROM users_roles
        WHERE
            users_id = user_id_in
            AND roles_id = ANY(role_ids_to_remove);
    END IF;

    UPDATE users
    SET
        agency_id = NULL,
        last_modified_date = NOW()
    WHERE
        id = user_id_in;
END;
$$
LANGUAGE plpgsql;


CREATE OR REPLACE FUNCTION get_listings_by_agent(p_agent_id INT)
    RETURNS TABLE (
                      listing_id INT,
                      title VARCHAR,
                      description text,
                      address VARCHAR,
                      rooms INT,
                      bathrooms INT,
					  price numeric(38,2),
                      listingOperation varchar,
                      area DOUBLE PRECISION,
                      energy_class VARCHAR,
                      longitude DOUBLE PRECISION,
                      latitude DOUBLE PRECISION,
                      thumbnail_url VARCHAR
                  )
AS $$
BEGIN
    RETURN QUERY
        SELECT
            l.listing_id,
            l.title,
            l.description,
			l.address,
            l.rooms,
            l.bathrooms,
			l.price,
            l.listing_operation,
            l.area,
            l.energy_class,
            ST_X(l.coordinate) AS longitude,
            ST_Y(l.coordinate) AS latitude,
            (
                SELECT url
                FROM listing_image li
                WHERE li.listing_id = l.listing_id
                ORDER BY COALESCE(li.sort_order, 0) ASC
                LIMIT 1
            ) AS thumbnail_url
        FROM
            listing l
        WHERE
            l.listed_by_agent_id = p_agent_id;
END;
$$ LANGUAGE plpgsql;


